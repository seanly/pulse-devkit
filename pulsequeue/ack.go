package pulsequeue

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/seanly/pulse-devkit/pulse"
)

// Ack reacts to an agent's accept or decline of a dispatched job.
//
// It is called from a stream's receive loop, which also carries that agent's
// heartbeats, so it must not block on anything slow. The store calls here are
// single-row writes; anything heavier belongs on its own goroutine.
func (d *Dispatcher) Ack(agentID, jobID string, accepted bool, reason, detail string) {
	if accepted {
		// Nothing to do: the lease already says the agent has it.
		return
	}
	// A declined job is not a failed job — no work was attempted — so it goes
	// back without burning an attempt.
	ctx := context.Background()
	j, err := d.jobs.GetJob(ctx, jobID)
	if err != nil {
		if !errors.Is(err, pulse.ErrNotFound) {
			d.log.Error("ack: load job", "job_id", jobID, "error", err)
		}
		return
	}

	switch reason {
	case pulse.AckBusy:
		// Another agent can run it right now.
		d.log.Debug("agent declined job as busy; requeueing", "job_id", jobID, "agent_id", agentID)
		d.requeue(ctx, j, declineText("agent busy", detail))
	case pulse.AckUnsupportedKind:
		// Re-dispatching to the same agent is pointless, and the application
		// chose this agent, so the requeue is a signal to it rather than a
		// retry that will work on its own.
		d.log.Warn("agent cannot execute this kind of job",
			"job_id", jobID, "agent_id", agentID, "kind", j.Kind)
		d.requeue(ctx, j, declineText("agent does not support kind "+j.Kind, detail))
	case pulse.AckRejected:
		d.log.Info("agent rejected job by local policy", "job_id", jobID, "agent_id", agentID)
		d.requeue(ctx, j, declineText("rejected by agent policy", detail))
	default:
		d.log.Warn("agent declined job with an unknown reason; requeueing",
			"job_id", jobID, "agent_id", agentID, "reason", reason)
		d.requeue(ctx, j, declineText("declined: "+reason, detail))
	}
	d.Wake()
}

func declineText(fallback, detail string) string {
	if detail == "" {
		return fallback
	}
	return fallback + ": " + detail
}

// Complete marks a dispatched job finished.
//
// Call it from a Sink after storing the result. ErrNotFound means the lease
// was already reclaimed and the report arrived too late, which is normal and
// not worth surfacing: treat it as "the queue has moved on".
func (d *Dispatcher) Complete(ctx context.Context, jobID string) error {
	err := d.jobs.Complete(ctx, jobID)
	switch {
	case err == nil:
		d.Wake()
		return nil
	case errors.Is(err, pulse.ErrNotFound):
		d.log.Debug("result for a job that is no longer leased; ignoring", "job_id", jobID)
		return nil
	default:
		return err
	}
}

// Fail records failed work, consuming one attempt. The job returns to the
// queue while attempts remain.
func (d *Dispatcher) Fail(ctx context.Context, jobID, reason string) error {
	err := d.jobs.Fail(ctx, jobID, reason)
	if err != nil && !errors.Is(err, pulse.ErrNotFound) {
		return err
	}
	d.Wake()
	return nil
}

// EnqueueInput is one job to queue.
type EnqueueInput struct {
	// AgentID is who should run it. The application decides this — see the
	// package documentation.
	AgentID string
	// GroupID and SubjectID are the application's own correlation handles.
	GroupID   string
	SubjectID string
	Kind      string
	// Payload is the work, opaque to the framework.
	Payload []byte
	// Timeout bounds one attempt. Zero means the dispatcher's default.
	Timeout time.Duration
	// MaxAttempts is the retry budget. Zero means 1 — one try, no retries.
	MaxAttempts int
}

// Enqueue queues jobs and asks for a dispatch pass.
//
// IDs are generated by newID; pass one in Options if the application needs
// them to match its own scheme.
func (d *Dispatcher) Enqueue(ctx context.Context, in []EnqueueInput, newID func() string) ([]pulse.Job, error) {
	if len(in) == 0 {
		return nil, nil
	}
	if newID == nil {
		return nil, errors.New("pulsequeue: newID is required")
	}
	now := d.now()
	jobs := make([]*pulse.Job, 0, len(in))
	for _, e := range in {
		if e.AgentID == "" {
			return nil, fmt.Errorf("pulsequeue: job for subject %q has no agent", e.SubjectID)
		}
		timeout := e.Timeout
		if timeout <= 0 {
			timeout = d.timeout
		}
		attempts := e.MaxAttempts
		if attempts <= 0 {
			attempts = 1
		}
		jobs = append(jobs, &pulse.Job{
			ID:          newID(),
			GroupID:     e.GroupID,
			SubjectID:   e.SubjectID,
			Kind:        e.Kind,
			AgentID:     e.AgentID,
			Status:      pulse.JobPending,
			Timeout:     timeout,
			MaxAttempts: attempts,
			Payload:     e.Payload,
			CreatedAt:   now,
		})
	}
	if err := d.jobs.Enqueue(ctx, jobs); err != nil {
		return nil, fmt.Errorf("pulsequeue: enqueue: %w", err)
	}
	// Fresh work should not wait a full tick.
	d.Wake()

	out := make([]pulse.Job, 0, len(jobs))
	for _, j := range jobs {
		out = append(out, *j)
	}
	return out, nil
}

// DispatchNow leases one specific job and pushes it immediately.
//
// For an operator's "run this now": leasing this job rather than running a
// whole pass means the request does not queue behind the agent's accumulated
// backlog. ErrConflict means the dispatch loop got there first and owns
// delivery — which is a success from the caller's point of view, not a
// failure.
func (d *Dispatcher) DispatchNow(ctx context.Context, jobID string) error {
	j, err := d.jobs.LeaseOne(ctx, jobID, d.leaseFor())
	if err != nil {
		return err
	}
	agent, err := d.agents.GetAgent(ctx, j.AgentID)
	if err != nil {
		// The job is leased but undeliverable; hand it straight back rather
		// than leaving it to time out.
		d.requeue(ctx, j, "agent lookup failed")
		return err
	}
	if !d.resolve(ctx, &j) {
		// The resolver already put the job where it belongs.
		return nil
	}
	if j.Timeout <= 0 {
		j.Timeout = d.timeout
	}
	if err := d.registry.SendTo(agent.ID, &pulse.ServerMessage{Job: &j}); err != nil {
		d.requeue(ctx, j, "push failed: "+err.Error())
		return fmt.Errorf("pulsequeue: push to %s: %w", agent.Name, err)
	}
	d.metrics.Inc(pulse.MetricJobsDispatched)
	d.log.Info("job dispatched on request", "job_id", j.ID, "agent", agent.Name)
	return nil
}
